function pickWords(count) {
  const shuffled = [...wordPool].sort(() => Math.random() - 0.5);
  // if count > wordPool length, cycle through again
  const result = [];
  while (result.length < count) {
    result.push(...shuffled);
  }
  return result.slice(0, count).join(" ");
}

export function getPassage(mode) {
  if (mode.endsWith("s")) {
    const timeCount = parseInt(mode);
    const words = timeCount === 60 ? 120 : 240;
    return pickWords(words);
  }
  const wordCount = parseInt(mode); // "25w" as 25, "50w" as 50, "100w" as 100
  return pickWords(wordCount);
}
